import numpy as np
import matplotlib.pyplot as plt
from mpl_toolkits.mplot3d import Axes3D

n = 100
x = np.linspace(-3, 3, n)
y = np.linspace(-3, 3, n)
X, Y = np.meshgrid(x, y)
Z = np.exp(-(X ** 2 + Y ** 2))

zmin, zmax = Z.min(), Z.max()
print(f"Z min = {zmin:.4f}, Z max = {zmax:.4f}")

fig = plt.figure(figsize=(16, 12))

ax1 = fig.add_subplot(2, 2, 1, projection='3d')
surf = ax1.plot_surface(X, Y, Z, cmap='hot', linewidth=0, antialiased=True, alpha=0.95)
ax1.set_xlabel('X')
ax1.set_ylabel('Y')
ax1.set_zlabel('Z')
ax1.set_title('z = exp(-(x^2 + y ^2)) — поверхность')
fig.colorbar(surf, ax=ax1, shrink=0.5, aspect=10)
ax1.view_init(elev=30, azim=45)

ax2 = fig.add_subplot(2, 2, 2, projection='3d')
ax2.plot_wireframe(X, Y, Z, rstride=5, cstride=5, color='darkred', linewidth=0.7)
ax2.set_xlabel('X')
ax2.set_ylabel('Y')
ax2.set_zlabel('Z')
ax2.set_title('Каркасный график ')
ax2.view_init(elev=30, azim=45)

ax3 = fig.add_subplot(2, 2, 3)
cf = ax3.contourf(X, Y, Z, levels=20, cmap='hot')
cs = ax3.contour(X, Y, Z, levels=10, colors='black', linewidths=0.5)
ax3.clabel(cs, inline=True, fontsize=8)
ax3.set_xlabel('X')
ax3.set_ylabel('Y')
ax3.set_title('Линии уровня')
fig.colorbar(cf, ax=ax3, shrink=0.8)

ax4 = fig.add_subplot(2, 2, 4, projection='3d')
ax4.plot_surface(X, Y, Z, cmap='hot', linewidth=0, antialiased=True, alpha=0.9)
ax4.contour(X, Y, Z, zdir='z', offset=zmin, cmap='hot', levels=15)
ax4.set_xlabel('X')
ax4.set_ylabel('Y')
ax4.set_zlabel('Z')
ax4.set_title('Поверхность + проекция линий уровня на z = zmin')
ax4.view_init(elev=25, azim=45)

plt.tight_layout()
plt.show()

fig = plt.figure(figsize=(10, 8))
