surf = ax.plot_surface(X, Y, Z, cmap='hot', linewidth=0, antialiased=True)
ax.set_xlabel('X')
ax.set_ylabel('Y')
ax.set_zlabel('Z')
ax.set_title('z = exp(-(x^2 + y ^2))')
fig.colorbar(surf, ax=ax, shrink=0.5, aspect=10)
ax.view_init(elev=30, azim=45)
plt.show()

fig = plt.figure(figsize=(10, 8))
ax = fig.add_subplot(111, projection='3d')
ax.plot_wireframe(X, Y, Z, rstride=5, cstride=5, color='darkred', linewidth=0.7)
ax.set_xlabel('X')
ax.set_ylabel('Y')
ax.set_zlabel('Z')
ax.set_title('Каркасный график')
ax.view_init(elev=30, azim=45)
