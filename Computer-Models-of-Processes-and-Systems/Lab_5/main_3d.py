ax.plot_surface(X, Y, Z, cmap='hot', linewidth=0, antialiased=True)
ax.contour(X, Y, Z, zdir='z', offset=zmin, cmap='hot', levels=15)
ax.set_xlabel('X')
ax.set_ylabel('Y')
ax.set_zlabel('Z')
ax.set_title('Поверхность + проекция линий уровня')
ax.view_init(elev=25, azim=45)
